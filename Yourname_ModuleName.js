    findBestNearestCinema(lat, lon, movie) {
        let nearestCinema;
        let shortestDistance = Infinity;

        for (let i = 0; i < this.showtime.length; i++) {
            if (movie.toLowerCase() === this.showtime[i].movie.toLowerCase()) {
                // convert lattitude and longitute to radians
                let userLat = lat * (Math.PI / 180);
                let userLon = lon * (Math.PI / 180);
                let cinemaLat = this.showtime[i].location.lat * (Math.PI / 180); //either yishun or bugis+ lat and lon 
                let cinemaLon = this.showtime[i].location.lon * (Math.PI / 180);
                console.log(this.showtime[i].cinema);
                let differenceLat = cinemaLat - userLat;
                let differenceLon = cinemaLon - userLon;


                let a =
                    Math.sin(differenceLat / 2) ** 2 +
                    Math.cos(userLat) *
                    Math.cos(cinemaLat) *
                    Math.sin(differenceLon / 2) ** 2;

                let c = 2 * Math.atan2(
                    Math.sqrt(a),
                    Math.sqrt(1 - a)
                );

                let distance = 6371 * c;
                //if the value is smaller, the shortestDistance variable will take the value
                if (distance < shortestDistance) {
                    shortestDistance = distance;
                    nearestCinema = {
                        cinema: this.showtime[i].cinema,
                        movie: this.showtime[i].movie,
                        distance: distance.toFixed(2)
                    };
                }
            }
        }

        if (!nearestCinema) {
            console.log("Movie not found!");
            return;
        }
        console.log("Recommended Cinema:", nearestCinema.cinema);
        console.log("Distance:", nearestCinema.distance + " km");

    },
    
